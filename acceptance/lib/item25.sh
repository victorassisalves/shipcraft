def run(*args):
    p = subprocess.run(args, input='', capture_output=True, text=True, timeout=90)
    print('$', shlex.join(args), '[rc=' + str(p.returncode) + ']\n' + p.stdout + p.stderr, flush=True)
    return p, p.stdout + p.stderr

def ok(*args):
