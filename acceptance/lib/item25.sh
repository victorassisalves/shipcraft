    integrated(tool, before, out)
    if missing:
        instruction = 'npx husky' if tool == 'husky' else 'pre-commit install -t commit-msg -t post-commit'
        assert sum(instruction in line for line in out.splitlines()) == 1, 'warning missing or repeated: ' + instruction
    if kind in ('min', 'min-alto'):
        cfg = tomli.loads(Path('.shipcraft.toml').read_text())
        if kind == 'min-alto': assert cfg['shipcraft_min'] == minimum, 'lowered a higher minimum'
        assert {k:v for k,v in cfg.items() if k != 'shipcraft_min'} == {k:v for k,v in old_config.items() if k != 'shipcraft_min'}, 'changed the rest of the TOML'
        assert '# comentário do projeto' in Path('.shipcraft.toml').read_text()
    if kind == 'ciclo':
        # Real launchers/h; exit 0 after the insertion must not skip the judgment.
        ok('git', 'add', '-A'); ok('git', 'commit', '-qm', 'chore: integração')
        write('textutil.py', 'def slugify(text):\n    raise NotImplementedError\n')
