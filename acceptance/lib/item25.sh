            if kind == 'igual-flow-stages':
                CONFIG.write_text(re.sub(r'stages:\n( *)- (commit-msg|post-commit)', r'stages: [\2]', CONFIG.read_text()))
            elif kind == 'igual-reordenado':
                data = yaml.safe_load(CONFIG.read_text())
                CONFIG.write_text(yaml.safe_dump(data, sort_keys=True))
        elif kind == 'diferente':
            add_pair()
            data = yaml.safe_load(CONFIG.read_text())
            h = next(h for repo in data['repos'] for h in repo['hooks'] if h['id'] == part[2])
            key = part[3]
            h[key] = {'entry': 'shipcraft check', 'name': 'outro', 'language': 'script', 'always_run': False,
                      'pass_filenames': True, 'stages': ['pre-commit'], 'extra': True}[key]
            CONFIG.write_text(yaml.safe_dump(data, sort_keys=False))
            refuse, reason = True, part[2]
        elif kind == 'shipcraft-pre':
            CONFIG.write_text(BASE_YAML.replace('entry: echo lint', 'entry: shipcraft check'))
            refuse, reason = True, 'pre-commit'
    if part[0] == 'yaml':
        raw = BASE_YAML
        if kind in ('cr', 'crlf', 'ls', 'ps'): raw = raw.replace('\n', {'cr':'\r', 'crlf':'\r\n', 'ls':'\u2028', 'ps':'\u2029'}[kind])
        elif kind == 'bom': raw = '\ufeff' + raw
        elif kind == 'comentario': raw = raw.replace('repos:', 'repos: # lista')
        elif kind == 'literal': raw = raw.replace('echo lint', "'echo \"{...} <<: &ancora\"'")
        elif kind == 'flow-outros': raw += '        args: [a, b]\n'
        else:
            refuse = True
            raw = {'repos-flow': 'repos: [{repo: local, hooks: []}]\n', 'repos-ausente':'default_stages: [pre-commit]\n',
                   'repos-nulo':'repos: null\n', 'repos-tipo':'repos: texto\n', 'repetida': BASE_YAML + 'repos:\n  - repo: local\n    hooks: []\n',
                   'repetida-hook': BASE_YAML + '        entry: shipcraft check\n',
                   'ancora': BASE_YAML.replace('repos:', 'repos: &repos'),
                   'merge': BASE_YAML.replace('  - repo: local', '  - <<: {repo: local}'),
                   'aspas': BASE_YAML.replace('repos:', '"repos":'), 'fim': BASE_YAML + '...\n', 'invalido': 'repos: [\n'}[kind]
        CONFIG.write_bytes(raw.encode())
    if kind.startswith('manual-shipcraft'):
        # Manual hook, no marker of its own; not a made-up tool launcher.
        write('.git/hooks/pre-commit', '#!/bin/sh\n'+('exec ' if kind.endswith('-exec') else '')+'shipcraft check\n', 0o755)
        refuse, reason = True, 'pre-commit'
    elif kind == 'duplo-fonte':
        root,hidden,localname,ext=part[2:]
        path=('.config/' if root=='config' else '')+('.' if hidden=='oculto' else '')+'lefthook'+('-local' if localname=='local' else '')+'.'+ext
        raw = ('[pre-commit.commands.lint]\nrun = "echo lint"\n' if ext=='toml' else
               '{"pre-commit":{"commands":{"lint":{"run":"echo lint"}}}}\n' if ext in ('json','jsonc') else
