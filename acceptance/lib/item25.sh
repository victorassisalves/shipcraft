        write(path,raw)
        refuse=True
    elif kind == 'duplo-pre':
        if tool == 'husky': CONFIG.write_text(BASE_YAML)
        else: write('.husky/pre-commit', 'echo lint\n')
        refuse = True
    elif kind == 'duplo-lefthook':
        write('lefthook.yml', 'pre-commit:\n  commands:\n    lint:\n      run: echo lint\n')
        refuse = True
    elif kind in ('min', 'min-alto', 'rollback'):
        cfg = Path('.shipcraft.toml')
        old_config = tomli.loads(cfg.read_text())
        current = tuple(map(int, PACKAGE_VERSION.split('.')))
        minimum = '0.0' if kind != 'min-alto' else str(current[0]+1) + '.0'
        cfg.write_text(re.sub(r'^shipcraft_min\s*=.*$', 'shipcraft_min = "' + minimum + '"', cfg.read_text(), flags=re.M) + '\n# comentário do projeto\n')
