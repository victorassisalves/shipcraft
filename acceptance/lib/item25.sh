# Full rule 25.3, c036098: pre-commit 4.3.0 decides the stages.
STAGES25 = {'ausente': None, 'vazio': [], 'pre-commit': ['pre-commit'],
            'commit': ['commit'], 'push': ['push'], 'manual': ['manual'],
            'merge-commit': ['merge-commit']}
BAD25 = {'nulo': None, 'texto': 'pre-commit', 'bool': False, 'numero': 1,
         'mapa': {}, 'numeros': [1], 'mista': ['pre-commit', 1], 'nulos': [None]}
ENTRY25 = {'simples': 'shipcraft check', 'absoluto': '/usr/local/bin/shipcraft check',
           'relativo': './bin/shipcraft check --x', 'aspas': "'shipcraft' check",
           'espacos': 'shipcraft  check', 'caminho-espaco': "'./pasta com espaço/shipcraft' check",
           'wrapper': 'shipcraft-wrapper check', 'status': 'shipcraft status', 'exec': 'exec shipcraft check',
