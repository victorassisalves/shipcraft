def rule3_config(part):
    kind = part[1]
    h = dict(id='regra3', name='hook do projeto', entry='shipcraft check',
             language='system', always_run=True, pass_filenames=False)
    top = {}; invalid = False; remote = False
    if kind == 'estagios':
        stage, default = part[2:]
        if stage != 'ausente': h['stages'] = copy.deepcopy(STAGES25[stage])
        if default != 'ausente': top['default_stages'] = copy.deepcopy(STAGES25[default])
    elif kind == 'estagios-lista':
        mixed = ['manual', 'push', 'pre-commit', 'merge-commit']
        if part[2] == 'hook':
            h['stages'] = mixed; top['default_stages'] = []
        elif part[2] == 'default':
            h['stages'] = []; top['default_stages'] = mixed
        elif part[2] == 'alias':
            h['stages'] = ['manual', 'commit', 'push']
        else:
            h['stages'] = ['manual', 'push']; top['default_stages'] = mixed
    elif kind == 'estagios-tipo':
        field, bad, entry = part[2:]
        h['entry'] = 'shipcraft check' if entry == 'check' else 'shipcraft status'
        if field == 'hook': h['stages'] = copy.deepcopy(BAD25[bad])
        else: top['default_stages'] = copy.deepcopy(BAD25[bad])
        invalid = True
    elif kind == 'default-tipo-com-stage':
        h['stages'] = ['pre-commit']
        top['default_stages'] = copy.deepcopy(BAD25[part[2]])
        invalid = True
    elif kind == 'entry':
        remote = part[2] == 'remoto'
        h['entry'] = ENTRY25[part[3]]
        h['stages'] = ['pre-commit']
    elif kind == 'entry-remoto-ausente':
        remote = True; h.pop('entry'); h['stages'] = ['pre-commit']
    elif kind == 'instalados':
        top['default_install_hook_types'] = {'vazio': [], 'commit-msg': ['commit-msg'], 'pre-push': ['pre-push']}[part[2]]
        h['stages'] = ['pre-commit']
    else:
        raise AssertionError('unknown rule 3 case: '+str(part))
    repo = {'repo': 'https://example.invalid/red25c-hooks', 'rev': 'v1', 'hooks': [h]} if remote else {'repo': 'local', 'hooks': [h]}
    top['repos'] = [repo]
    duplicate = False
    if not invalid:
        # [] on the hook inherits; an explicit [] at the top does NOT inherit all.
        stages = h.get('stages') or top.get('default_stages', ['pre-commit'])
        aliases = {'commit': 'pre-commit', 'push': 'pre-push', 'merge-commit': 'pre-merge-commit'}
        pre = 'pre-commit' in [aliases.get(s, s) for s in stages]
        words = shlex.split(h.get('entry', ''))
        duplicate = pre and len(words) >= 2 and Path(words[0]).name == 'shipcraft' and words[1] == 'check'
    return top, invalid, duplicate

def rule3_case(part):
    install('pre')
    data, invalid, duplicate = rule3_config(part)
    remote = data['repos'][0]['repo'] != 'local'
    marker = None
    if remote:
        # Do not fetch a manifest even when entry is absent from the file.
        bindir = Path(shutil.which('codex')).parent
        if part[1] == 'entry-remoto-ausente':
            repo = bindir / 'manifesto-remoto'
            repo.mkdir()
            (repo / '.pre-commit-hooks.yaml').write_text(yaml.safe_dump([
                dict(id='regra3', name='remoto', entry='shipcraft check', language='system', stages=['pre-commit'])]))
            for args in [('init','-q'), ('add','.'), ('-c','user.name=RED','-c','user.email=red@example.invalid','commit','-qm','fixture')]:
                p = subprocess.run(['git','-C',str(repo),*args], capture_output=True)
                assert p.returncode == 0, p.stderr
            data['repos'][0]['repo'] = repo.as_uri()
            data['repos'][0]['rev'] = 'HEAD'
        realgit = shutil.which('git')
        marker = bindir / 'manifesto-lido'
        watcher = ('#!/bin/sh\nfor arg do\n case "$arg" in clone|fetch|ls-remote) '
                   'printf "%s\\n" "$*" >> '+shlex.quote(str(marker))+'; exit 97 ;; esac\ndone\nexec '+shlex.quote(realgit)+' "$@"\n')
        write(bindir / 'git', watcher, 0o755)
    CONFIG.write_text(yaml.safe_dump(data, sort_keys=False))
    before = snapshot()
    p,out = run('shipcraft','init')
    if invalid or duplicate:
        refusal(p,out,before)
        if invalid:
            assert str(CONFIG) in out and re.search(r'(read|permission|invalid|understand)', out, re.I), 'invalid type was not refused as an unreadable file'
            assert '`shipcraft check` in pre-commit' not in out, 'invalid type mistaken for duplication'
        if duplicate:
            assert re.search(r'(remove)',out.splitlines()[-1],re.I), 'does not say to remove shipcraft check from pre-commit'
    else:
        assert p.returncode == 0, 'refused a pre-commit hook that is not shipcraft check'
        integrated('pre',before,out)
    if marker:
        assert not marker.exists(), 'tried to fetch a remote manifest'


def main(case):
    part = case.split('.')
    if part[0] == 'trava': return lock_case(part)
    if part[1] in ('estagios','estagios-lista','estagios-tipo','default-tipo-com-stage','entry','entry-remoto-ausente','instalados'): return rule3_case(part)
    tool = 'pre' if part[0] in ('pre', 'yaml') else 'husky'
    kind = part[1]
    if kind in ('min', 'min-alto', 'rollback') or kind.startswith('status-'):
        ok('shipcraft', 'init')
        Path('.git/hooks/pre-commit').unlink(missing_ok=True)
    if kind.startswith('antigo-sem-dir-'):
        # Without installing Husky 9: the old signals must be enough on their own.
        if kind.endswith('-path'):
            ok('git', 'config', 'core.hooksPath', '.husky')
        else:
            manifest={'husky': {'hooks': {'pre-commit': 'echo lint'}}}
            if kind.endswith('-package'): manifest['devDependencies']={'husky':'4.3.8'}
            write('package.json', json.dumps(manifest)+'\n')
        assert not Path('.husky').exists()
        before=snapshot()
        p,out=run('shipcraft','init','--lang','python')
        refusal(p,out,before,'9')
        return
    install(tool, integrated=kind.startswith('status-'))
    refuse, reason, missing = False, None, False
    if tool == 'husky':
        if kind in ('exec', 'exit', 'shebang', 'sem-quebra', 'comentario', 'ciclo'):
            for e in EVENTS:
                text = {'exec': 'exec echo fim\n', 'exit': 'exit 0\n', 'ciclo': 'exit 0\n', 'shebang': '#!/bin/sh\nexit 0\n',
                        'sem-quebra': 'echo sem-quebra', 'comentario': '# shipcraft outro\necho "shipcraft ignorado"\n'}[kind]
                write('.husky/' + e, text)
        elif kind in ('igual', 'parcial'):
            for e in EVENTS if kind == 'igual' else EVENTS[:1]:
                write('.husky/' + e, '#!/bin/sh\n# existente\n' + LINES[e] + '\necho fim\n')
        elif kind == 'ausente':
            for e in EVENTS: Path('.husky/' + e).unlink()
        elif kind == 'launchers-ausentes':
            for e in EVENTS: Path('.husky/_/' + e).unlink()
            missing = True
        elif kind == 'h-vazio':
            write('.husky/_/h', '')
            refuse, reason = True, 'npx husky'
        elif kind == 'antigo-package':
            write('package.json', '{"husky":{"hooks":{"pre-commit":"echo lint"}}}')
            refuse, reason = True, '9'
        elif kind == 'antigo-path':
            ok('git', 'config', 'core.hooksPath', '.husky')
            refuse, reason = True, '9'
        elif kind == 'path-sem-h':
            Path('.husky/_/h').unlink()
            refuse = True
        elif kind in ('outro-shipcraft', 'link', 'ilegivel', 'binario'):
