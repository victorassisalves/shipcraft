                        if h['id'] == hook(event)['id']: h['always_run'] = False
                CONFIG.write_text(yaml.safe_dump(data, sort_keys=False))
        if kind in ('status-launcher', 'status-sem-exec'):
            path = Path(('.husky/_/' if tool == 'husky' else '.git/hooks/') + event)
            if kind == 'status-launcher': path.unlink()
            else: path.chmod(0o644)
        before = snapshot()
        p, out = run('shipcraft', 'status')
        assert p.returncode == 0
        if kind == 'status-completo': assert 'hook through ' + ('husky' if tool == 'husky' else 'pre-commit') + ' (commit-msg)' in out.lower(), 'status did not recognize the full integration'
        else:
            assert 'missing hook' in out.lower() and 'hook through ' + ('husky' if tool == 'husky' else 'pre-commit') not in out.lower(), 'status announces an incomplete integration'
            assert event in out, 'status does not name the missing event'
        assert snapshot() == before, 'status wrote files'
        return
    before = snapshot()
    p, out = run('shipcraft', 'init', *(['--github'] if kind == 'rollback' else []))
    if refuse:
        refusal(p, out, before, reason)
        if kind == 'shipcraft-pre' or kind.startswith('manual-shipcraft'): assert re.search(r'(remove)', out.splitlines()[-1], re.I), 'did not say to remove the duplicate shipcraft check'
        return
    if kind == 'rollback':
        assert p.returncode != 0 and '.shipcraft/locks' in out, 'did not reach the later transaction failure'
        assert not Path('.github').exists(), 'init created .github (item 27)'
        assert snapshot() == before, 'rollback does not restore bytes/modes/config'
        return
