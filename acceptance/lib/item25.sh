        if kind in ('sem-launchers', 'parcial-launchers'):
            for e in EVENTS if kind == 'sem-launchers' else EVENTS[:1]: Path('.git/hooks/' + e).unlink()
            missing = True
        elif kind in ('outro-config', 'alheio', 'link'):
            p = Path('.git/hooks/commit-msg')
