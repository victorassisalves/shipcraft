            if kind == 'outro-shipcraft': p.write_text('shipcraft check --outra-opcao\n')
            elif kind == 'link':
                p.unlink(); p.symlink_to('arquivo-externo')
            elif kind == 'ilegivel': p.chmod(0)
            else: p.write_bytes(b'echo oi\x00\xff')
